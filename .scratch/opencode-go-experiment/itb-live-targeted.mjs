#!/usr/bin/env node
// Targeted live validation on REAL smart-building-itb content (user-approved,
// max 8 requests). Proves the model route on ITB workbooks:
//   1. an ambiguous-flagged XLSX group (must return a validator-accepted
//      sheet_interpretation for the group to pass), and
//   2. a structured XLSX group (merges with the /39 deterministic rows).
// Phase A captures the exact attempt-1 production prompts offline; phase B
// sends each prompt once through the capped dispatcher; phase C replays the
// live responses OFFLINE through the real pipeline and records the validator
// outcome. Key from .env.opencode-go.local, never printed. Demo fixture data
// only (workbook is generated by the project's own tracker-web tool).
import { readFileSync, writeFileSync, mkdirSync, unlinkSync } from "node:fs";
import { createRequire } from "node:module";
import { dirname, join } from "node:path";
import { pathToFileURL, fileURLToPath } from "node:url";
import { randomUUID } from "node:crypto";

const require = createRequire(import.meta.url);
const ts = require("typescript");

const MAX_REQUESTS = Number(process.env.LIVE_MAX_REQUESTS ?? "8");
const MAX_OUTPUT_TOKENS = 4096;
const REASONING_HEADROOM_TOKENS = 4096;
const MAX_INPUT_CHARS = Number(process.env.LIVE_MAX_INPUT_CHARS ?? "12000");
const PROVIDER_BASE = "https://opencode.ai/zen/go/v1";
const WORKBOOK =
  "demo-evidence-fixtures/smart-building-itb/sessions/2026-10-09_w4/11_Pengelolaan_Utilitas_Subcontractor_Weekly.xlsx";
const OUT = ".local-evaluation/final-testing/itb-live";
mkdirSync(OUT, { recursive: true });

let envKey = null;
try {
  const match = /^OPENCODE_GO_API_KEY=(.+)$/m.exec(readFileSync(".env.opencode-go.local", "utf8"));
  if (match) envKey = match[1].trim();
} catch {}
if (!envKey) {
  console.error("FATAL: OPENCODE_GO_API_KEY not configured; 0 requests sent.");
  process.exit(3);
}

const src = (rel) => fileURLToPath(new URL(`../../${rel}`, import.meta.url));
const compile = (source) =>
  ts.transpileModule(readFileSync(source, "utf8"), {
    compilerOptions: { module: ts.ModuleKind.ESNext, target: ts.ScriptTarget.ES2022 },
  }).outputText;
const emit = (rel, rewrites = []) => {
  const source = src(rel);
  const target = join(dirname(source), `.itb-live-${randomUUID()}-${rel.split("/").pop().replace(".ts", "")}.mjs`);
  let code = compile(source);
  for (const [from, to] of rewrites) code = code.replace(`from "${from}"`, `from "${to}"`);
  writeFileSync(target, code);
  return target;
};
const cleanup = [];
let parseDocumentBuffer = null;
let extractDocumentGroups = null;
try {
  const zipSafety = emit("src/features/documents/lib/zip-safety.ts"); cleanup.push(zipSafety);
  const constants = emit("src/features/documents/lib/constants.ts"); cleanup.push(constants);
  const costEvidence = emit("src/features/assurance/lib/cost-evidence.ts"); cleanup.push(costEvidence);
  const sourceValue = emit("src/features/documents/lib/source-value-validation.ts"); cleanup.push(sourceValue);
  const guards = emit("worker/src/types/guards.ts"); cleanup.push(guards);
  const parser = emit("worker/src/services/document-parser.ts", [
    ['../../../../src/features/documents/lib/zip-safety', pathToFileURL(zipSafety).href],
    ['../../../src/features/documents/lib/zip-safety', pathToFileURL(zipSafety).href],
  ]); cleanup.push(parser);
  const extraction = emit("worker/src/services/document-extraction.ts", [
    ['../../../src/features/documents/lib/constants', pathToFileURL(constants).href],
    ['../../../src/features/assurance/lib/cost-evidence', pathToFileURL(costEvidence).href],
    ['../../../src/features/documents/lib/source-value-validation', pathToFileURL(sourceValue).href],
    ['../types/guards', pathToFileURL(guards).href],
  ]); cleanup.push(extraction);
  ({ parseDocumentBuffer } = await import(pathToFileURL(parser).href));
  ({ extractDocumentGroups } = await import(pathToFileURL(extraction).href));
} finally {
  for (const path of cleanup) { try { unlinkSync(path); } catch {} }
}
if (typeof extractDocumentGroups !== "function" || typeof parseDocumentBuffer !== "function") {
  console.error("FATAL: production modules did not load.");
  process.exit(3);
}

const isAnalysisTask = (prompt) => /^Task: analyze this bounded group/m.test(prompt);
const isDomainTask = (prompt) => /^Task: collect every source-backed cost and assurance observation/m.test(prompt);
const isClassification = (prompt) => prompt.startsWith("Classify the entire document");
const isExecutiveSummary = (prompt) => prompt.startsWith("Create a concise whole-document assurance summary");
const taskLabel = (prompt) => isClassification(prompt) ? "classification"
  : isExecutiveSummary(prompt) ? "executive_summary"
  : isAnalysisTask(prompt) ? "analysis_task"
  : isDomainTask(prompt) ? "domain_task" : "unknown";
const groupOf = (prompt) => Number(/group (\d+) and global/.exec(prompt)?.[1] ?? -1);
const isCorrection = (prompt) => prompt.includes("Previous response validation errors");

// Minimal task answers used OFFLINE only (capture + replay of non-target groups).
function minimalAnalysis(prompt, { withInterpretation = false } = {}) {
  const refs = JSON.parse(/^SOURCE_REFERENCES_JSON=(.+)$/m.exec(prompt)[1]);
  const source = refs[0];
  const answer = {
    facts: [],
    summary: { summary_text: "Offline minimal answer.", confidence: 0.5, quality_warning: null, sources: [{ source_id: source.source_id }] },
    health_snapshots: ["overall", "schedule", "cost", "risk", "governance", "audit_readiness"].map((dimension) => ({
      dimension, score: null, status: "insufficient_evidence", evidence_coverage: null,
      status_text: "No validated status.", source_summary: "No evidence.", snapshot_date: null, source_id: null,
    })),
    alerts: [], actions: [],
    group_metadata_suggestions: { suggested_document_date: null, detected_reporting_period: null, suggested_workstream: null, source_id: null },
  };
  if (withInterpretation) {
    answer.sheet_interpretation = {
      interpretation_status: "unknown",
      structure_type: "unknown",
      sheet_name: source.source_location?.sheetName ?? "unknown",
      source_ids: [source.source_id],
      header_candidates: [],
      column_roles: [],
      candidate_observations: [],
      warnings: ["Offline minimal stub; the live response replaces this for the target group."],
    };
  }
  return answer;
}
function minimalDomain() {
  return {
    cost_observations: [],
    assurance_observations: { milestones: [], progress: [], risk_snapshots: [], risk_register_statements: [] },
  };
}

// --- phase A: capture attempt-1 prompts per group (offline) -------------------
const buffer = readFileSync(WORKBOOK);
const arrayBuffer = buffer.buffer.slice(buffer.byteOffset, buffer.byteOffset + buffer.byteLength);
const parsed = await parseDocumentBuffer(WORKBOOK.split("/").pop(), arrayBuffer);
if (!parsed.ok) {
  console.error("FATAL: parse failed", parsed.errorCode);
  process.exit(3);
}
const captured = new Map(); // `${kind}:${group}` -> { url, body, prompt }
const savedFetch = globalThis.fetch;
globalThis.fetch = async (url, init = {}) => {
  const body = JSON.parse(String(init.body));
  const prompt = body.messages?.[1]?.content ?? "";
  const kind = isAnalysisTask(prompt) ? "analysis" : isDomainTask(prompt) ? "domain" : taskLabel(prompt);
  if ((isAnalysisTask(prompt) || isDomainTask(prompt)) && !isCorrection(prompt)) {
    const key = `${kind}:${groupOf(prompt)}`;
    if (!captured.has(key)) captured.set(key, { url: String(url), body, prompt });
  }
  if (isAnalysisTask(prompt)) {
    // Ambiguous groups need some sheet_interpretation for the pipeline to move
    // on; the stub keeps capture cheap. Non-ambiguous groups get none.
    return new Response(JSON.stringify({ choices: [{ message: { content: JSON.stringify(minimalAnalysis(prompt, { withInterpretation: true })) }, finish_reason: "stop" }] }), { status: 200 });
  }
  if (isDomainTask(prompt)) {
    return new Response(JSON.stringify({ choices: [{ message: { content: JSON.stringify(minimalDomain()) }, finish_reason: "stop" }] }), { status: 200 });
  }
  if (isExecutiveSummary(prompt)) {
    const input = JSON.parse(/^EXECUTIVE_SUMMARY_INPUT_JSON=(.+)$/m.exec(prompt)[1]);
    return new Response(JSON.stringify({ choices: [{ message: { content: JSON.stringify({ summary_text: "- Capture.", confidence: 0.5, source_indexes: [input.sources[0].source_index] }) }, finish_reason: "stop" }] }), { status: 200 });
  }
  const refs = JSON.parse(/^SOURCE_REFERENCES_JSON=(.+)$/m.exec(prompt)?.[1] ?? "[]");
  return new Response(JSON.stringify({ choices: [{ message: { content: JSON.stringify({
    document_suggestions: {
      suggested_document_type: "progress_report", suggested_evidence_role: "current",
      classification_confidence: 0.9, classification_reason: "Capture classification.",
      source_id: refs[0]?.source_id ?? null,
    },
    quality_warning: null,
  }) }, finish_reason: "stop" }] }), { status: 200 });
};
try {
  process.env.XASS_LLM_PROVIDER = "openai-compatible";
  process.env.XASS_CLOUD_LLM_API_KEY = "unused-captured-only";
  process.env.XASS_CLOUD_LLM_BASE_URL = PROVIDER_BASE;
  process.env.XASS_CLOUD_LLM_MODEL = "capture";
  await extractDocumentGroups(
    { jobId: "itb-capture", projectId: "itb", documentId: "capture", fileName: WORKBOOK.split("/").pop(), title: "Capture",
      documentTypeHint: null, documentDateHint: null, reportingPeriodHint: null, workstreamHint: null, fileBuffer: arrayBuffer },
    parsed.chunks, parsed.parserMetadata,
    { async loadGroups() { return []; }, async saveGroup(row) { return row; } },
  );
} finally {
  globalThis.fetch = savedFetch;
  delete process.env.XASS_LLM_PROVIDER;
  delete process.env.XASS_CLOUD_LLM_API_KEY;
  delete process.env.XASS_CLOUD_LLM_BASE_URL;
  delete process.env.XASS_CLOUD_LLM_MODEL;
}

// Targets: first ambiguous group (analysis prompt carries the interpretation
// schema) and first structured group (no interpretation schema, XLSX rows).
let ambiguous = null;
let structured = null;
for (const [key, entry] of captured) {
  if (!key.startsWith("analysis:")) continue;
  const group = groupOf(entry.prompt);
  if (entry.prompt.includes('"sheet_interpretation"') && !ambiguous) ambiguous = { group, ...entry };
  if (!entry.prompt.includes('"sheet_interpretation"') && !structured &&
      entry.prompt.includes('"source_location"')) structured = { group, ...entry };
}
console.log(`captured ${captured.size} prompts; ambiguous group=${ambiguous?.group ?? "none"}, structured group=${structured?.group ?? "none"}`);
if (!ambiguous || !structured) {
  console.error("FATAL: targets not found.");
  process.exit(3);
}

// --- phase B: live, capped dispatcher -----------------------------------------
const MODEL = process.env.OPENCODE_GO_MODEL ?? "glm-5.3-flash";
const ledger = [];
let requests = 0;
let stopped = null;
class StopError extends Error {}
const stop = (reason) => { if (!stopped) stopped = reason; };
const realFetch = globalThis.fetch;
function persistLedger() {
  writeFileSync(join(OUT, "live-attempts.jsonl"), ledger.map((row) => JSON.stringify(row)).join("\n") + "\n");
}
async function sendLive(entry, label) {
  if (stopped) throw new StopError(`stopped: ${stopped}`);
  if (requests >= MAX_REQUESTS) {
    stop("request_limit_reached");
    throw new StopError("stopped: request_limit_reached");
  }
  const promptChars = Buffer.byteLength(entry.prompt, "utf8");
  if (promptChars > MAX_INPUT_CHARS) {
    stop(`input_chars_${promptChars}`);
    throw new StopError(`stopped: input ${promptChars} chars exceeds ${MAX_INPUT_CHARS}`);
  }
  if (!entry.url.startsWith(`${PROVIDER_BASE}/`)) {
    stop("unexpected_capture_url");
    throw new StopError(`stopped: captured URL is not the approved endpoint: ${entry.url.slice(0, 80)}`);
  }
  requests += 1;
  const t0 = performance.now();
  const response = await realFetch(entry.url, {
    method: "POST",
    headers: {
      "Content-Type": "application/json",
      Authorization: `Bearer ${envKey}`,
      "x-opencode-session": process.env.OPENCODE_GO_SESSION ?? `itb-live-${randomUUID().slice(0, 8)}`,
      "User-Agent": "devxassurance-itb-live/1.0",
    },
    body: JSON.stringify({ ...entry.body, model: MODEL, stream: false, max_tokens: MAX_OUTPUT_TOKENS + REASONING_HEADROOM_TOKENS }),
    signal: AbortSignal.timeout(120000),
  }).catch((error) => {
    stop(`dispatch_failed: ${error instanceof Error ? (error.cause?.code ?? error.message) : String(error)}`.slice(0, 120));
    throw error;
  });
  const latencyMs = Math.round(performance.now() - t0);
  let envelope = null;
  try { envelope = await response.clone().json(); } catch {}
  const choice = envelope?.choices?.[0] ?? null;
  const usage = envelope && typeof envelope.usage === "object" ? envelope.usage : null;
  const visibleTokens = usage ? usage.completion_tokens - (usage.completion_tokens_details?.reasoning_tokens ?? 0) : null;
  const record = {
    n: requests, task: label, model: envelope?.model ?? MODEL, prompt_chars: promptChars,
    status: response.status, latencyMs,
    usage: usage ? { prompt_tokens: usage.prompt_tokens ?? null, completion_tokens: usage.completion_tokens ?? null, reasoning_tokens: usage.completion_tokens_details?.reasoning_tokens ?? null, visible: visibleTokens } : null,
    finish_reason: choice?.finish_reason ?? null,
  };
  ledger.push(record);
  persistLedger();
  console.log(`[${record.n}/${MAX_REQUESTS}] ${label} HTTP ${record.status} ${latencyMs}ms in=${usage?.prompt_tokens ?? "?"} out=${usage?.completion_tokens ?? "?"} finish=${record.finish_reason}`);
  if (response.status === 401 || response.status === 403 || response.status === 404 || response.status === 429) {
    stop(`http_${response.status}`);
    throw new StopError(`stopped: HTTP ${response.status}`);
  }
  if (record.finish_reason === "length") {
    stop("truncated_output");
    throw new StopError("stopped: finish_reason=length");
  }
  if (!response.ok) {
    stop(`http_${response.status}`);
    throw new StopError(`stopped: HTTP ${response.status}`);
  }
  if (visibleTokens !== null && visibleTokens >= MAX_OUTPUT_TOKENS) {
    stop("output_token_cap_hit");
    throw new StopError("stopped: visible completion reached the output token cap");
  }
  return typeof choice?.message?.content === "string" ? choice.message.content : "";
}

const live = {};
const targets = [];
if (process.env.LIVE_SKIP_AMBIGUOUS !== "1") targets.push([ambiguous, "ambiguous"]);
if (process.env.LIVE_INCLUDE_STRUCTURED !== "0") targets.push([structured, "structured"]);
try {
  for (const [target, tag] of targets) {
    for (const kind of ["analysis", "domain"]) {
      const entry = captured.get(`${kind}:${target.group}`);
      const content = await sendLive(entry, `${tag}_g${target.group}_${kind}`);
      live[`${tag}:${kind}`] = content;
      writeFileSync(join(OUT, `response-${tag}-g${target.group}-${kind}.json`), content + "\n");
    }
  }
} catch (error) {
  console.log(`STOPPED: ${stopped ?? String(error?.message ?? error).slice(0, 200)}`);
}

// --- phase C: offline replay through the real pipeline ------------------------
const outcome = { model: MODEL, requests_sent: requests, max_requests: MAX_REQUESTS, stopped, targets: {} };
const liveResponseFor = (tag, target, kind) => {
  const key = `${tag}:${kind}`;
  if (live[key]) return { content: live[key], live: true };
  const path = join(OUT, `response-${tag}-g${target.group}-${kind}.json`);
  try {
    const content = readFileSync(path, "utf8");
    return { content, live: true };
  } catch {
    return { content: null, live: false };
  }
};
const liveTargets = {};
const liveFetch = async (_url, init) => {
  const body = JSON.parse(String(init.body));
  const prompt = body.messages?.[1]?.content ?? "";
  const group = groupOf(prompt);
  const kind = isAnalysisTask(prompt) ? "analysis" : isDomainTask(prompt) ? "domain" : taskLabel(prompt);
  if (kind === "analysis" || kind === "domain") {
    for (const [tag, target] of [["ambiguous", ambiguous], ["structured", structured]]) {
      if (group === target.group) {
        const resolved = liveResponseFor(tag, target, kind);
        if (resolved.content) {
          liveTargets[tag] = true;
          return new Response(JSON.stringify({ message: { content: resolved.content } }), { status: 200 });
        }
      }
    }
    if (kind === "analysis") {
      const flagged = prompt.includes('"sheet_interpretation"');
      return new Response(JSON.stringify({ message: { content: JSON.stringify(minimalAnalysis(prompt, { withInterpretation: flagged })) } }), { status: 200 });
    }
    return new Response(JSON.stringify({ message: { content: JSON.stringify(minimalDomain()) } }), { status: 200 });
  }
  if (kind === "executive_summary") {
    const input = JSON.parse(/^EXECUTIVE_SUMMARY_INPUT_JSON=(.+)$/m.exec(prompt)[1]);
    return new Response(JSON.stringify({ message: { content: JSON.stringify({ summary_text: "- ITB replay.", confidence: 0.5, source_indexes: [input.sources[0].source_index] }) } }), { status: 200 });
  }
  const refs = JSON.parse(/^SOURCE_REFERENCES_JSON=(.+)$/m.exec(prompt)?.[1] ?? "[]");
  return new Response(JSON.stringify({ message: { content: JSON.stringify({
    document_suggestions: {
      suggested_document_type: "progress_report", suggested_evidence_role: "current",
      classification_confidence: 0.9, classification_reason: "Replay classification.", source_id: refs[0]?.source_id ?? null,
    },
    quality_warning: null,
  }) } }), { status: 200 });
};
process.env.XASS_LLM_PROVIDER = "ollama";
process.env.OLLAMA_BASE_URL = "http://replay.invalid";
process.env.OLLAMA_MODEL = "replay";
globalThis.fetch = liveFetch;
const rows = new Map();
try {
  const result = await extractDocumentGroups(
    { jobId: "itb-replay", projectId: "itb", documentId: "replay", fileName: WORKBOOK.split("/").pop(), title: "ITB replay",
      documentTypeHint: null, documentDateHint: null, reportingPeriodHint: null, workstreamHint: null, fileBuffer: arrayBuffer },
    parsed.chunks, parsed.parserMetadata,
    { async loadGroups() { return [...rows.values()]; }, async saveGroup(row) { rows.set(row.groupKey, row); } },
  );
  const checkpointFor = (target) => [...rows.values()]
    .filter((row) => target.group >= (row.groupIndex ?? -1) && row.groupIndex === target.group)
    .map(({ status, lastError }) => ({ status, lastError: lastError ? String(lastError).slice(0, 220) : null }));
  outcome.targets.ambiguous = {
    group: ambiguous.group,
    live_response_replayed: Boolean(liveTargets.ambiguous),
    checkpoints: checkpointFor(ambiguous),
  };
  outcome.targets.structured = {
    group: structured.group,
    live_response_replayed: Boolean(liveTargets.structured),
    checkpoints: checkpointFor(structured),
  };
  outcome.pipeline_ok = result.ok;
  outcome.document_quality_warnings = result.ok ? result.extraction.quality_warnings.slice(0, 6) : null;
  outcome.deterministic_progress_rows = result.ok ? result.extraction.assurance_observations.progress.length : null;
  outcome.facts = result.ok ? result.extraction.facts.slice(0, 6).map(({ fact_type, extracted_text }) => ({ fact_type, extracted_text: extracted_text.slice(0, 140) })) : null;
  outcome.notes = [
    "classification/summary and all non-target groups are offline mocks; only the two target groups' analysis+domain responses are live model output",
    "correction loops re-serve the same live response offline; attempt counts are validator retries, not provider calls",
  ];
} catch (error) {
  outcome.replay_crash = String(error?.message ?? error).slice(0, 300);
} finally {
  globalThis.fetch = savedFetch;
  delete process.env.XASS_LLM_PROVIDER;
  delete process.env.OLLAMA_BASE_URL;
  delete process.env.OLLAMA_MODEL;
}
writeFileSync(join(OUT, "itb-live-summary.json"), JSON.stringify(outcome, null, 2) + "\n");
console.log(JSON.stringify(outcome, null, 2));
